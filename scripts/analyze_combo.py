"""Pellav2, VeriSpoof-Plus and four ways of combining them, graded on hard set 3 (voice clones).

Protocol 1 "tune on easy, face clones": combos and cut-offs fitted on sets 1+2, graded on set 3.
Protocol 2 "tune on clones": 5-fold cross-validation inside set 3; a person and their clone are
always in the same fold, so no voice is ever both tuned on and graded on.
Ranges are 95% bootstrap ranges that resample whole voices.

Writes results/combo_protocol1.csv, combo_protocol2.csv, combo_by_condition.csv.
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from vad_bench.combo import COMBOS, bootstrap_ci, cv_predictions, fit_combo, operating_points  # noqa: E402
from vad_bench.metrics import auc  # noqa: E402

BUILT_IN = {"Pellav2 alone": 0.0, "VeriSpoof-Plus alone": 0.0}  # rule combos and learned weighting: 0.5
N_BOOT = 500


def pairs(path, set_tag):
    s = pd.read_csv(ROOT / path)
    s = s[s.model.isin(["Pellav2", "VeriSpoof-Plus"])]
    meta = [c for c in s.columns if c not in ("model", "ai_score")]
    p = s.pivot_table(index="file", columns="model", values="ai_score").rename(
        columns={"Pellav2": "pella", "VeriSpoof-Plus": "veri"})
    d = s.drop_duplicates("file").set_index("file")[meta[1:]].join(p).reset_index()
    if "voice_id" not in d:
        d["voice_id"] = set_tag + ":" + d.file.map(lambda f: Path(f).stem)
    return d


def rates(d, called):
    ai, hu = d.is_ai == 1, d.is_ai == 0
    return float(np.mean(called[ai])), float(np.mean(~called[hu]))


def with_ci(d, called_col):
    a, h = rates(d, d[called_col].values)
    (alo, ahi) = bootstrap_ci(d, lambda x: float(x[called_col][x.is_ai == 1].mean()), n=N_BOOT)
    (hlo, hhi) = bootstrap_ci(d, lambda x: float(1 - x[called_col][x.is_ai == 0].mean()), n=N_BOOT)
    return {"ai_caught": a, "ai_lo": alo, "ai_hi": ahi, "humans_passed": h, "hu_lo": hlo, "hu_hi": hhi}


f = lambda v, lo, hi: f"{100 * v:.0f}% ({100 * lo:.0f}–{100 * hi:.0f})"

train = pd.concat([pairs("results/scores.csv", "s1"), pairs("results/scores_b.csv", "s2")], ignore_index=True)
c_all = pairs("results/scores_c.csv", "s3")
restored = c_all[c_all.kind == "fleurs"]  # AI-restored FLEURS-R humans: reported separately, not in the test
test = pd.concat([c_all[c_all.kind != "fleurs"], pairs("results/scores_c_orig.csv", "s3")], ignore_index=True)
print(f"train: {len(train)} clips; test: {len(test)} clips, {test.voice_id.nunique()} voices")

# ---------------- protocol 1
rows, cond = [], []
for name in COMBOS:
    m = fit_combo(name, train)
    s_tr, s_te = m(train), m(test)
    ops = operating_points(s_tr, train.is_ai, s_te, test.is_ai, built_in=BUILT_IN.get(name, 0.5))
    for op in ops.itertuples():
        t = test.assign(called=s_te >= op.cutoff)
        rows.append({"combo": name, "cutoff_kind": op.cutoff_kind, "cutoff": op.cutoff,
                     "auc": auc(s_te, test.is_ai.values), **with_ci(t, "called")})
        for (ch, k), g in t.groupby(["channel", "is_ai"]):
            cond.append({"protocol": 1, "combo": name, "cutoff_kind": op.cutoff_kind, "channel": ch,
                         "is_ai": k, "share_called_ai": g.called.mean()})
p1 = pd.DataFrame(rows)
p1.to_csv(ROOT / "results/combo_protocol1.csv", index=False)

# ---------------- protocol 2
rows = []
oof_all = {}
for name in COMBOS:
    o = cv_predictions(test, name, k=5, seed=0)
    oof_all[name] = o
    for kind, col in [("≤5% humans flagged", "cutoff_5"), ("≤1% humans flagged", "cutoff_1")]:
        t = o.assign(called=o.score >= o[col])
        rows.append({"combo": name, "cutoff_kind": kind, "auc": auc(o.score.values, o.is_ai.values),
                     **with_ci(t, "called")})
        for (ch, k), g in t.groupby(["channel", "is_ai"]):
            cond.append({"protocol": 2, "combo": name, "cutoff_kind": kind, "channel": ch,
                         "is_ai": k, "share_called_ai": g.called.mean()})
p2 = pd.DataFrame(rows)
p2.to_csv(ROOT / "results/combo_protocol2.csv", index=False)
pd.DataFrame(cond).to_csv(ROOT / "results/combo_by_condition.csv", index=False)
pd.concat([o.assign(combo=n) for n, o in oof_all.items()]).to_csv(ROOT / "results/combo_protocol2_scores.csv", index=False)

# ---------------- side finding: humans whose audio was regenerated by an AI restoration model
side = []
for name in ["Pellav2 alone", "VeriSpoof-Plus alone", "either flags", "average", "learned weighting"]:
    m = fit_combo(name, train)
    op = p1[(p1.combo == name) & (p1.cutoff_kind == "≤5% humans flagged")].cutoff.iloc[0]
    for label, d in [("original recordings", test[test.kind == "fleurs original"]), ("AI-restored (FLEURS-R)", restored)]:
        side.append({"combo": name, "humans": label, "passed": float(np.mean(m(d) < op))})
side = pd.DataFrame(side)
side.to_csv(ROOT / "results/combo_restored_humans.csv", index=False)
print("\n== Same people, same sentences: share passed as human (protocol 1, ≤5% cut-off)")
print(side.pivot(index="combo", columns="humans", values="passed").mul(100).round(0).to_string())

for title, p in [("PROTOCOL 1: tuned on sets 1+2, graded on clone set 3", p1),
                 ("PROTOCOL 2: tuned on other voices in set 3 (5-fold), graded on held-out voices", p2)]:
    print(f"\n== {title}")
    print(pd.DataFrame({"combo": p.combo, "cut-off": p.cutoff_kind,
                        "AI caught": [f(*r) for r in zip(p.ai_caught, p.ai_lo, p.ai_hi)],
                        "humans passed": [f(*r) for r in zip(p.humans_passed, p.hu_lo, p.hu_hi)],
                        "AUC": p.auc.round(3)}).to_string(index=False))
